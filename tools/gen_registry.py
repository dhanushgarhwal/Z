#!/usr/bin/env python3
"""Generates installer/registry.inc (Explorer menus, file associations, Default Apps capabilities).
Run after editing the tables below:  python tools/gen_registry.py"""
import os
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "installer", "registry.inc")

# extension -> task that controls it
ASSOC = {
    "zip": "assoc_zip", "7z": "assoc_7z", "rar": "assoc_rar",
    "tar": "assoc_tar", "tgz": "assoc_tar", "tbz2": "assoc_tar", "txz": "assoc_tar", "tzst": "assoc_tar",
    "gz": "assoc_single", "bz2": "assoc_single", "xz": "assoc_single", "zst": "assoc_single",
}
EXE = '{app}\\Z.exe'
lines = ["; AUTO-GENERATED by tools/gen_registry.py - do not edit by hand.", "[Registry]"]

def q(s): return '"' + s.replace('"', '""') + '"'
def reg(sub, name=None, data="", typ="string", tasks=None, flags=None):
    p = [f"Root: HKA", f"Subkey: {q(sub)}", f"ValueType: {typ}"]
    if name is not None: p.append(f"ValueName: {q(name)}")
    p.append(f"ValueData: {q(data)}")
    if flags: p.append(f"Flags: {flags}")
    if tasks: p.append(f"Tasks: {tasks}")
    lines.append("; ".join(p))

def key(sub, tasks, flags="uninsdeletekey"):
    lines.append("; ".join(["Root: HKA", f"Subkey: {q(sub)}", "ValueType: none", f"Flags: {flags}", f"Tasks: {tasks}"]))

def cascade(base, tasks, items):
    """Classic cascading submenu: <base>\\Z with nested shell\\<verb>\\command."""
    key(base, tasks)
    reg(base, "MUIVerb", "Z", tasks=tasks)
    reg(base, "Icon", f'"{EXE}",0', tasks=tasks)
    reg(base, "SubCommands", "", tasks=tasks)
    for i, (label, args) in enumerate(items):
        v = f"{base}\\shell\\{i:02d}"
        reg(v, "MUIVerb", label, tasks=tasks)
        reg(f"{v}\\command", None, f'"{EXE}" {args}', tasks=tasks)

# ---- right-click on any file / folder: add to archive
ADD = [
    ("Add to archive...", 'a --dialog --collect "%1"'),
    ("Add to .zip",       'a -f zip --collect "%1"'),
    ("Add to .7z",        'a -f 7z --collect "%1"'),
    ("Add to .tar.zst",   'a -f tar.zst --collect "%1"'),
]
for base in ("Software\\Classes\\*\\shell\\Z", "Software\\Classes\\Directory\\shell\\Z"):
    cascade(base, "ctx_all", ADD)

# ---- right-click on an archive: open / extract
ARC = [
    ("Open with Z",        '"%1"'),
    ("Extract here",       'x --here --collect "%1"'),
    ("Extract to folder",  'x --to-folder --collect "%1"'),
    ("Extract files...",   'x --ask --collect "%1"'),
]
for ext in ASSOC:
    cascade(f"Software\\Classes\\SystemFileAssociations\\.{ext}\\shell\\Z", "ctx_archive", ARC)

# ---- ProgID + associations (Z is added to 'Open with' and to Settings > Default apps)
PROG = "Software\\Classes\\Z.Archive"
key(PROG, "assoc_zip assoc_7z assoc_rar assoc_tar assoc_single")
for t in ("assoc_zip assoc_7z assoc_rar assoc_tar assoc_single",):
    reg(PROG, None, "Z archive", tasks=t)
    reg(f"{PROG}\\DefaultIcon", None, '{app}\\z-archive.ico', tasks=t)
    reg(f"{PROG}\\shell\\open\\command", None, f'"{EXE}" "%1"', tasks=t)
for ext, task in ASSOC.items():
    reg(f"Software\\Classes\\.{ext}\\OpenWithProgids", "Z.Archive", "", tasks=task, flags="uninsdeletevalue")
    reg(f"Software\\Classes\\.{ext}", None, "Z.Archive", tasks=task, flags="createvalueifdoesntexist")
    reg("Software\\Z\\Capabilities\\FileAssociations", f".{ext}", "Z.Archive", tasks=task)
ALL = "assoc_zip assoc_7z assoc_rar assoc_tar assoc_single"
reg("Software\\Z\\Capabilities", "ApplicationName", "Z", tasks=ALL)
reg("Software\\Z\\Capabilities", "ApplicationIcon", f'{EXE},0', tasks=ALL)
reg("Software\\RegisteredApplications", "Z", "Software\\Z\\Capabilities", tasks=ALL, flags="uninsdeletevalue")
key("Software\\Z", ALL)

open(OUT, "w", encoding="utf-8", newline="\r\n").write("\n".join(lines) + "\n")
print(f"wrote {OUT}: {len(lines)} lines")
